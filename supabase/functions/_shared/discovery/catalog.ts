import type { DiscoveryItem } from "./types.ts";
import { CATEGORY_FAMILY } from "./taxonomy.ts";

function item(
  partial: Omit<DiscoveryItem, "family"> & { family?: DiscoveryItem["family"] }
): DiscoveryItem {
  return {
    ...partial,
    family: partial.family ?? CATEGORY_FAMILY[partial.category],
  };
}

