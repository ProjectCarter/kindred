/**
 * Turn edition local events into discovery candidates.
 */
export function localEventsAsDiscoveryItems(
  events: Array<{
    name: string;
    startDateTime: string;
    venue: string;
    city: string;
    sourceUrl?: string;
    sourceName?: string;
  }>
): DiscoveryItem[] {
  return events.slice(0, 12).map((e, i) => {
    const hay = `${e.name} ${e.venue}`.toLowerCase();
    let category: DiscoveryItem["category"] = "experiences";
    if (/museum|gallery|exhibit/.test(hay)) category = "museums";
    else if (/hike|trail|walk/.test(hay)) category = "hiking";
    else if (/park|garden/.test(hay)) category = "parks";
    else if (/beach|shore|coast/.test(hay)) category = "beaches";
    else if (/coffee|cafe|café/.test(hay)) category = "coffee";
    else if (/restaurant|dinner|food|market/.test(hay)) category = "restaurants";

    const idBase = e.name
      .toLowerCase()
      .replace(/[^a-z0-9]+/g, "_")
      .slice(0, 40);

    return item({
      id: `event_${idBase}_${i}`,
      title: e.name.trim(),
      dek: `${e.venue}${e.city ? ` · ${e.city}` : ""} — ${e.startDateTime}`,
      category,
      place: { city: e.city || null },
      source: {
        name: e.sourceName?.trim() || "Local listing",
        tier: "local",
        url: e.sourceUrl ?? null,
      },
      url: e.sourceUrl ?? null,
      tags: ["local_event", "local"],
      seasons: ["anytime"],
      weatherFit: ["any"],
      popularity: 0.4,
      uniqueness: 0.55,
      localExpertise: 0.9,
      quality: 0.7,
    });
  });
}

/** Foursquare category → Discovery Engine category. No schema changes:
 *  bookstores read naturally as a Notebook "books" find; attractions read
 *  as a Notebook "experiences" find. Coffee/restaurants/parks/museums/
 *  scenic_drives already have a matching category 1:1. */
const PLACE_CATEGORY_MAP: Record<string, DiscoveryItem["category"]> = {
  coffee: "coffee",
  restaurants: "restaurants",
  parks: "parks",
  museums: "museums",
  scenic_drives: "scenic_drives",
  bookstores: "books",
  attractions: "experiences",
};

/**
 * Verified local places (Foursquare) → discovery candidates. Every field
 * traces back to the cached provider record — Kindred never invents a
 * business, address, or fact here. `note` is Kindred's own editorial
 * voice, already written from those verified facts (see places/notes.ts),
 * never a stand-in for missing data.
 */
export function localPlacesAsDiscoveryItems(
  places: Array<{
    providerId: string;
    name: string;
    category: string;
    address: string | null;
    city: string | null;
    url: string | null;
    note?: string | null;
  }>
): DiscoveryItem[] {
  return places.map((p) => {
    const category = PLACE_CATEGORY_MAP[p.category] ?? "experiences";
    return item({
      id: `place_${p.providerId}`,
      title: p.name,
      dek:
        p.note?.trim() ||
        [p.address, p.city].filter(Boolean).join(" — ") ||
        "A verified local place.",
      category,
      place: { city: p.city ?? null },
      source: {
        name: "Foursquare",
        tier: "local",
        url: p.url ?? null,
      },
      url: p.url ?? null,
      tags: ["local_place", "verified"],
      seasons: ["anytime"],
      weatherFit: ["any"],
      popularity: 0.35,
      uniqueness: 0.4,
      localExpertise: 0.85,
      quality: 0.65,
    });
  });
}
